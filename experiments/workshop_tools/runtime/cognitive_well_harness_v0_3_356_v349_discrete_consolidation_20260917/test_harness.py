    def test_budget_forcing_binds_stage_model_and_markdown(self) -> None:
        text = _proposal()
        call = _forcing(
            text=text,
            stage=certificate.CERTIFICATE_AUTHOR_STAGE,
            model="fake-gemma",
        )
        verified = certificate.validate_markdown_budget_forcing(
            call,
            expected_stage=certificate.CERTIFICATE_AUTHOR_STAGE,
            expected_model="fake-gemma",
            canonical_markdown=text,
        )
        self.assertTrue(verified["canonical_artifacts_are_forced_response"])
        for mutation in ("stage", "model", "forced_text_sha256"):
            tampered = {
                **call,
                "metadata": {
                    "v0257_budget_forcing": {
                        **call["metadata"]["v0257_budget_forcing"],
                        mutation: "tampered",
                    }
                },
            }
            with self.subTest(mutation=mutation):
                with self.assertRaises(ValueError):
                    certificate.validate_markdown_budget_forcing(
                        tampered,
                        expected_stage=certificate.CERTIFICATE_AUTHOR_STAGE,
                        expected_model="fake-gemma",
                        canonical_markdown=text,
                    )

    def test_budget_forcing_explicit_timeout_configuration(self) -> None:
        text = _proposal()
        call = _forcing(text=text, stage="rewrite", model="fake-gemma")
        call["request_timeout_sec"] = 900
        call["metadata"]["config"] = {"timeout_seconds": 900}
        kwargs = dict(expected_stage="rewrite", expected_model="fake-gemma", canonical_markdown=text)
        with self.assertRaises(ValueError):
            certificate.validate_markdown_budget_forcing(call, **kwargs)
        certificate.validate_markdown_budget_forcing(call, expected_timeout_sec=900, **kwargs)
        call["metadata"]["config"]["timeout_seconds"] = 600
        with self.assertRaises(ValueError):
            certificate.validate_markdown_budget_forcing(call, expected_timeout_sec=900, **kwargs)

    def test_budget_forcing_no_deadline_requires_explicit_none(self) -> None:
        text = _proposal()
        call = _forcing(text=text, stage="rewrite", model="fake-gemma")
        call["request_timeout_sec"] = None
        call["metadata"]["config"] = {"timeout_seconds": None}
        kwargs = dict(expected_stage="rewrite", expected_model="fake-gemma", canonical_markdown=text)
        certificate.validate_markdown_budget_forcing(call, expected_timeout_sec=None, **kwargs)
        with self.assertRaises(ValueError):
            certificate.validate_markdown_budget_forcing(call, **kwargs)
        del call["metadata"]["config"]["timeout_seconds"]
        with self.assertRaises(ValueError):
            certificate.validate_markdown_budget_forcing(call, expected_timeout_sec=None, **kwargs)
        call["metadata"]["config"]["timeout_seconds"] = None
        del call["request_timeout_sec"]
        with self.assertRaises(ValueError):
            certificate.validate_markdown_budget_forcing(call, expected_timeout_sec=None, **kwargs)

    def test_provider_rejects_proposal_drift_and_missing_forcing(self) -> None:
        context = _context(self.root)
        proposal_path = self.root / "proposal.md"
        proposal_path.write_text(_proposal(), encoding="utf-8")
        call = _forcing(
            text=_proposal(),
            stage=certificate.CERTIFICATE_AUTHOR_STAGE,
            model="fake-gemma",
        )
        provider = certificate.ModelAuthoredVerifiedCertificateProvider(
            context=context,
            proposal_path=proposal_path,
            expected_proposal_sha256=base.sha256_text(_proposal()),
            expected_exact_replay_sha256=certificate.exact_tools.stable_hash(
                EXACT_REPLAY
            ),
            expected_source_artifact_sha256={
                label: base.sha256_file(path)
                for label, path in sorted(context.source_artifacts.items())
            },
            expected_model="fake-gemma",
            producer_call=call,
        )
        self.assertEqual(provider.materialize().verdict, "VERIFIED_SUPPORT")
        proposal_path.write_text(_proposal() + "\n<!-- drift -->\n", encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "proposal hash drift"):
            provider.materialize()
        proposal_path.write_text(_proposal(), encoding="utf-8")
        without_forcing = replace(provider, producer_call={})
        with self.assertRaisesRegex(ValueError, "lacks mandatory budget forcing"):
            without_forcing.materialize()

