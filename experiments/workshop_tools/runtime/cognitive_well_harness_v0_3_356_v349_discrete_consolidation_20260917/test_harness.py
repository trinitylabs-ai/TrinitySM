THEOREM = "If x=y and y^2=1, prove x^2=1."
ARGUMENTS = {
    "symbols": ["x", "y"],
    "generators": {
        "D1": {"sub": [{"symbol": "x"}, {"symbol": "y"}]},
        "D2": {"sub": [{"pow": [{"symbol": "y"}, 2]}, 1]},
    },
    "target": {"sub": [{"pow": [{"symbol": "x"}, 2]}, 1]},
}
EXACT_REPLAY = {
    "schema": "synthetic-replay-v1",
    "operation": "polynomial_ideal_membership",
    "claim": "x^2-1 belongs to the ideal generated by x-y and y^2-1",
    "verified": True,
    "verdict": "VERIFIED_SUPPORT",
}


def _program() -> dict[str, Any]:
    return {
        "semantics": {
            "formal_source": "D1 and D2 are exactly the two theorem hypotheses.",
            "target_meaning": "C1 is x^2-1=0, equivalently x^2=1.",
            "guard_use": "The frozen y_nonzero condition records y is nonzero.",
            "proof_consequence": "C1 is the requested conclusion.",
            "required_conclusion": "x^2=1",
        },
        "symbols": ["x", "y"],
        "relations": ["D1", "D2"],
        "definitions": [],
        "zeros": [{"label": "C1", "value": ARGUMENTS["target"], "scale": 1,
                   "combination": {"add": [
                       {"mul": [{"add": [{"symbol": "x"}, {"symbol": "y"}]}, {"symbol": "D1"}]},
                       {"symbol": "D2"}]}}],
        "identities": [
            {
                "label": "I1",
                "left": {
                    "sub": [
                        {"pow": [{"symbol": "x"}, 2]},
                        {"pow": [{"symbol": "y"}, 2]},
                    ]
                },
                "right": {
                    "mul": [
                        {"sub": [{"symbol": "x"}, {"symbol": "y"}]},
                        {"add": [{"symbol": "x"}, {"symbol": "y"}]},
                    ]
                },
            }
        ],
        "conclusion": {
            "label": "C1",
            "left": ARGUMENTS["target"],
            "right": 0,
        },
        "guards": ["y_nonzero"],
    }


def _proposal() -> str:
    return protocol.render_program(_program())


def _context(
    tmp_path: Path,
    *,
    replay: Mapping[str, Any] | None = None,
) -> certificate.GenericCertificateContext:
    tmp_path.mkdir(parents=True, exist_ok=True)
    source = tmp_path / "source_request.md"
    source.write_text("# Frozen typed request\n\nD1, D2, and target are bound.\n", encoding="utf-8")
    exact = tmp_path / "exact_result.md"
    exact.write_text("# Exact result\n\nThe independently replayed result is affirmative.\n", encoding="utf-8")
    frozen_replay = dict(EXACT_REPLAY if replay is None else replay)
    return certificate.GenericCertificateContext(
        certificate_id="synthetic_x_square",
        theorem=THEOREM,
        arguments=ARGUMENTS,
        typed_guards={"y_nonzero": {"symbol": "y"}},
        replay_formal_request=lambda: dict(ARGUMENTS),
        replay_exact=lambda: dict(frozen_replay),
        formal_request_markdown=source.read_text(encoding="utf-8").strip(),
        exact_result_markdown=exact.read_text(encoding="utf-8").strip(),
        source_artifacts={"formal_request": source, "exact_result": exact},
    )


def _task() -> TaskInputs:
    return TaskInputs(
        problem_id="synthetic_x_square",
        theorem=THEOREM,
        source_proof=(
            "Let x and y satisfy the two stated hypotheses. We seek the displayed "
            "square identity, using no assumptions beyond those hypotheses."
        ),
        additional_documents={},
    )


def _forcing(*, text: str, stage: str, model: str) -> dict[str, Any]:
    cue = "Continue the deep reasoning and return one complete Markdown replacement."
    return {
        "attempt": 1,
        "cap": 32768,
        "request_timeout_sec": 600,
        "metadata": {
            "v0257_budget_forcing": {
                "schema": certificate.EXPECTED_BUDGET_FORCING_SCHEMA,
                "policy": certificate.EXPECTED_BUDGET_FORCING_POLICY,
                "stage": stage,
                "model": model,
                "structured": False,
                "cue": cue,
                "cue_sha256": base.sha256_text(cue),
                "forced_text_sha256": base.sha256_text(text),
                "canonical_artifacts_are_forced_response": True,
            }
        },
    }


def _audit_markdown() -> str:
    checks = "\n".join(
        f"- {label}: PASS" for label in proof_protocol.PROOF_AUDIT_CHECKS
    )
    return f"# Decision\n\nPASS\n\n# Checks\n\n{checks}\n\n# Issues\n\nNONE"


def _proof_markdown() -> str:
    details = "\n\n".join(
        (
            f"For bookkeeping step {index}, retain the hypotheses "
            r"\(x=y\) and \(y^2=1\); substituting the first equality into the "
            r"left side gives \(x^2=y^2\), while the second equality fixes that "
            r"common value as \(1\)."
        )
        for index in range(1, 7)
    )
    return f"""# Proof

Let (x,y) satisfy (x=y) and (y^2=1). We retain both equations with their
original meanings and make no division.

{details}

[[VERIFIED_EXACT_EVIDENCE]]

The displayed final equality is (x^2-1=0). Adding (1) to both sides gives
(x^2=1), exactly the requested conclusion."""


class FakeModelCall:
    def __init__(self, proposal: str) -> None:
        self.proposal = proposal
        self.outputs: list[tuple[str, str]] = []

    def __call__(self, **kwargs: Any) -> tuple[str, Any, dict[str, Any]]:
        destination = Path(kwargs["destination"])
        destination.mkdir(parents=True, exist_ok=False)
        stage = str(kwargs["stage"])
        if stage == certificate.CERTIFICATE_AUTHOR_STAGE:
            text = self.proposal
        elif stage.endswith("_audit"):
            text = _audit_markdown()
        else:
            text = _proof_markdown()
        parsed = kwargs["parser"](text)
        self.outputs.append((stage, text))
        return text, parsed, _forcing(
            text=text,
            stage=stage,
            model=kwargs["role"].model,
        )


